#!/usr/bin/env python3
"""
Generate src/launcher/hijri.js: a compact Umm al-Qura month table for the car's
old browser, which has no built-in Hijri calendar.

Each entry is the first day of a Hijri month, as days since 1970-01-01.
Covers 1445 AH (2023) to 1480 AH (2057). Requires: hijridate
"""
import datetime
import os

from hijridate import Hijri

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIRST_YEAR, LAST_YEAR = 1445, 1480
EPOCH = datetime.date(1970, 1, 1)

starts = []
for y in range(FIRST_YEAR, LAST_YEAR + 1):
    for m in range(1, 13):
        g = Hijri(y, m, 1).to_gregorian()
        starts.append((datetime.date(g.year, g.month, g.day) - EPOCH).days)
# one extra entry: start of the month after the last one, to bound the table
g = Hijri(LAST_YEAR + 1, 1, 1).to_gregorian()
starts.append((datetime.date(g.year, g.month, g.day) - EPOCH).days)

js = """/* Umm al-Qura calendar table, generated by tools/gen_hijri.py — do not edit by hand.
 * MONTH_STARTS[i] = first day of Hijri month i (counted from %d/1), in days since 1970-01-01. */
var Home2Hijri = {
    FIRST_YEAR : %d,
    MONTH_STARTS : [%s],
    fromDate : function(d)
    {
        var days = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
        var s = this.MONTH_STARTS;
        if (days < s[0] || days >= s[s.length - 1]) { return null; }
        var lo = 0, hi = s.length - 2;
        while (lo < hi)
        {
            var mid = Math.ceil((lo + hi) / 2);
            if (s[mid] <= days) { lo = mid; } else { hi = mid - 1; }
        }
        return { year : this.FIRST_YEAR + Math.floor(lo / 12), month : (lo %% 12) + 1, day : days - s[lo] + 1 };
    }
};

""" % (FIRST_YEAR, FIRST_YEAR, ",".join(str(x) for x in starts))

out = os.path.join(ROOT, "src", "launcher", "hijri.js")
with open(out, "w", encoding="utf-8") as f:
    f.write(js)
print("wrote", out, len(starts), "entries")
